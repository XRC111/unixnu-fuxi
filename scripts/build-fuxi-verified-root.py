#!/usr/bin/env python3
"""Build the verified-root symbol stub archive for fuxi.

NativeUfs references three verified-root symbols at link time (drivers/ShengUfs/
NativeUfs.cpp includes VerifiedBlockPolicy.h whenever NATIVE_VERIFIED_BLOCK is
set, which the kernel build always sets for NativeUfs):

  * const NativeVerifiedBlockPolicy verified_root_policies[]
  * const uint64_t verified_root_policy_count
  * const uint8_t verified_root_key[VR_KEY_BYTES]
  * (and, in the verification path only: vr_open / vr_verify_block /
    vr_xnu_crypto, declared weak in NativeUfs.cpp)

fuxi has no signed root-policy bundle, so the table is generated empty and the
crypto entry points are defined as returning stubs. That is a truthful
statement, not a substitute that pretends to verify anything:

  * `NativeUfsBlock::configureVerification` returns before reading the key or
    calling `vr_open` when `verified_root_policy_count == 0`, so the driver runs
    with root verification disabled and says so through gRootDiagnostic.stage.
  * The UFS probes (native-ufs-probe=1..9) never reach that path at all: they
    adopt the controller and issue read-only SCSI commands without publishing
    any window.

The same situation is handled on other boards with a generated stub: Kerfand's
UniXNU-fuxi (scripts/fuxi-stub.c, iOS 16 target, different symbol types) and
UniXNU-shennong (scripts/build-verified-root.py, arm64e, the full kit compiled
with an empty table). This board is arm64 / iPadOS 17.7.11 and uses the current
ShengUfs symbol types, so the stub is generated here with the exact types of
drivers/VirtioMmioBlock/VerifiedBlockPolicy.h and include/verified_root.h:
the policy struct is declared locally (the C++-only header cannot be included
from a C compile record), and the key has VR_KEY_BYTES bytes.

The unit is compiled with the kernel's own C compile record and archived; the
board links it before component:ShengUfs so the driver's references resolve.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/fuxi-verified-root'
ARCHIVE = OUT / 'libFuxiVerifiedRoot.a'
RECIPE = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/osfmk/DEVELOPMENT/prng_random.o.json'

POLICY_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-fuxi-verified-root.py: this board has no signed policy
 * bundle, so the policy table is empty and the crypto entry points are stubs.
 * verified_root_policy_count == 0 makes NativeUfsBlock::configureVerification
 * return before it reads the key or calls vr_open, so root verification is
 * disabled rather than approximated. The UFS probes never reach that path.
 *
 * This unit reuses a C compile record, so it has to be valid C as well as C++:
 * it declares the policy struct itself instead of including the C++-only
 * VerifiedBlockPolicy.h, and it avoids nullptr. */
#include "verified_root.h"
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

struct NativeVerifiedBlockPolicy {
	const uint8_t *manifest;
	uint64_t manifestBytes;
};

/* extern is required: at namespace scope a const has internal linkage in C++,
 * and NativeUfs references both objects by name. */
extern const uint8_t verified_root_key[VR_KEY_BYTES];
const uint8_t verified_root_key[VR_KEY_BYTES] = {0};

extern const struct NativeVerifiedBlockPolicy verified_root_policies[];
const struct NativeVerifiedBlockPolicy verified_root_policies[1] = {
	{ 0, 0 },
};

extern const uint64_t verified_root_policy_count;
const uint64_t verified_root_policy_count = 0;

/* The verification-path entry points NativeUfs weak-references. With the empty
 * table above they are unreachable; the stubs keep the link satisfied should a
 * future build enable the path before a real bundle exists. */
int vr_open (const uint8_t *envelope, size_t envelopeBytes,
             const uint8_t key[VR_KEY_BYTES], uint64_t imageBytes,
             const struct vr_crypto *crypto, struct vr_view *view)
{
	(void) envelope; (void) envelopeBytes; (void) key; (void) imageBytes;
	(void) crypto; (void) view;
	return VR_FORMAT;
}

int vr_open_header (const uint8_t *envelope, size_t envelopeBytes,
                    const uint8_t key[VR_KEY_BYTES], uint64_t imageBytes,
                    const struct vr_crypto *crypto, struct vr_view *view)
{
	(void) envelope; (void) envelopeBytes; (void) key; (void) imageBytes;
	(void) crypto; (void) view;
	return VR_FORMAT;
}

int vr_verify_block (const struct vr_view *view, uint64_t block,
                     const void *data, size_t dataBytes,
                     const struct vr_crypto *crypto)
{
	(void) view; (void) block; (void) data; (void) dataBytes; (void) crypto;
	return VR_FORMAT;
}

const struct vr_crypto vr_xnu_crypto = {0};

#ifdef __cplusplus
}
#endif
'''


BOOT_PROGRESS_SOURCE = '''/* SPDX-License-Identifier: BSD-2-Clause-Patent */
/* Generated by build-fuxi-verified-root.py. NativeUfs declares this weak and
 * calls it only while verifying a root window; an observer that observes
 * nothing is the right definition until a board diagnostic supplies a real
 * one. */
void boot_progress_poll (void)
{
}
'''


def fail(message: str) -> None:
    raise SystemExit('build-fuxi-verified-root: ' + message)


def compile_environment(tree: Path) -> dict:
    """The environment kernel.py gives the archive builders, so the clang shim
    resolves on a Linux host; a macOS host passes its own environment through."""
    import os
    import platform
    if platform.system() != 'Linux':
        return dict(os.environ)
    toolchain = Path(os.environ.get('UNIXNU_TOOLCHAIN', '/opt/unixnu-linux'))
    clt = toolchain / 'CommandLineTools/usr'
    xctoolchain = toolchain / 'XcodeDefault.xctoolchain/usr'
    fakeroot = tree / '.cache/fakeroot'
    env = dict(os.environ)
    env.update({
        'PATH': os.pathsep.join([str(clt / 'bin'), str(toolchain / 'bin'), os.environ.get('PATH', '')]),
        'LC_ALL': 'C',
        'CLT_PREFIX': str(clt),
        'XCTOOLCHAIN_PREFIX': str(xctoolchain),
        'XNU_TOOLCHAIN_BIN': f'{clt / "bin"} {xctoolchain / "bin"}',
        'UNIXNU_SDKROOT': str(fakeroot),
        'UNIXNU_SDK_VERSION': '17.0',
        'UNIXNU_PLATFORM_PATH': str(fakeroot / 'Platforms/iPhoneOS.platform'),
        'CROSS_CLANG': str(toolchain / 'llvm/bin/clang'),
        'DARWIN_TRIPLE': 'arm64-apple-ios17.0',
        'CROSS_EXTRA_FLAGS': '-mllvm -disable-atexit-based-global-dtor-lowering',
        'CCC_OVERRIDE_OPTIONS': '# +-Wno-missing-designated-field-initializers +-Wno-unused-but-set-global',
    })
    return env


def command_for(record: dict, source: Path, destination: Path, includes: list) -> list:
    """The kernel's own compile flags, with the input and output swapped in."""
    command, index = [], 0
    arguments = record['arguments']
    while index < len(arguments):
        value = arguments[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value == '-Xclang' and index + 1 < len(arguments) and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    if '-o' not in command:
        command += ['-o', str(destination)]
    for include in includes:
        command += ['-I', str(include)]
    command += ['-Wno-error']
    return command


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('sources', nargs='*',
                        help='ignored; kept so board.toml entries stay uniform')
    parser.add_argument('--archive', type=Path, default=ARCHIVE, help='archive to write')
    args = parser.parse_args()
    del args.sources

    if not RECIPE.is_file():
        fail(f'missing {RECIPE}; run "unixnu build kernel" once to record the compiles')
    record = json.loads(RECIPE.read_text().strip().rstrip(','))
    OUT.mkdir(parents=True, exist_ok=True)

    includes = [ROOT / 'kits/VerifiedRoot/include',
                ROOT / 'drivers/VirtioMmioBlock',
                ROOT / '.cache/xnu-work/osfmk']
    generated = OUT / 'verified-policy.cpp'
    generated.write_text(POLICY_SOURCE)

    destination = OUT / 'verified-policy.o'
    command = command_for(record, generated, destination, includes)
    (OUT / 'verified-policy.compile-command.json').write_text(json.dumps(command, indent=2) + '\n')
    result = subprocess.run(command, cwd=record['directory'], env=compile_environment(ROOT),
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (OUT / 'verified-policy.compile.log').write_text(result.stdout or '')
    if result.returncode:
        fail('verified-policy.cpp did not compile:\n' + (result.stdout or '')[-3000:])

    args.archive.parent.mkdir(parents=True, exist_ok=True)
    args.archive.unlink(missing_ok=True)
    result = subprocess.run(['xcrun', 'ar', 'rcs', str(args.archive), str(destination)],
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        fail('ar failed: ' + (result.stdout or '') + (result.stderr or ''))
    print(f'build-fuxi-verified-root: {args.archive} (empty policy table, verification disabled)')


if __name__ == '__main__':
    raise SystemExit(main())
